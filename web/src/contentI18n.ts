export type ContentTextKey = keyof typeof EN;

export function contentText(
  key: ContentTextKey,
  locale: ContentLocale,
): string {
  return (locale === "zh-CN" ? ZH : EN)[key];
}

export function contentStatusText(status: string, locale: ContentLocale): string {
  const key = `status_${status}` as ContentTextKey;
  return key in EN ? contentText(key, locale) : status.replaceAll("_", " ");
}
